const MAX_RESULTS = 8;

export function normalizePublicSearch(value = "") {
  return String(value).normalize("NFKC").trim().toUpperCase();
}

function safeText(value) {
  return typeof value === "string" ? value.trim() : "";
}

function recordMatches(query, values) {
  return values.some((value) => normalizePublicSearch(value).includes(query));
}

function entriesOf(index) {
  if (Array.isArray(index)) return index;
  return Array.isArray(index?.records) ? index.records : [];
}

function companyCodeOf(record) {
  return safeText(record?.companyCode ?? record?.issuerCode ?? record?.term?.issuerCode);
}

function companyNameOf(record) {
  return safeText(record?.companyName ?? record?.issuerName ?? record?.term?.issuerName);
}

function bondCodeOf(record) {
  return safeText(record?.bondCode ?? record?.term?.bondCode);
}

function bondNameOf(record) {
  return safeText(record?.bondName ?? record?.term?.bondName);
}

export function buildCompanySearchResults(query, indexes = {}) {
  const needle = normalizePublicSearch(query);
  if (!needle) return [];
  const companies = new Map();
  const ensureCompany = (record) => {
    const code = companyCodeOf(record);
    const label = companyNameOf(record);
    if (!/^\d{4}$/.test(code) || !label) return null;
    const current = companies.get(code);
    if (current) return current;
    const next = { code, label, bonds: [] };
    companies.set(code, next);
    return next;
  };

  for (const record of Array.isArray(indexes.emerging) ? indexes.emerging : []) ensureCompany(record);
  for (const record of Array.isArray(indexes.ipo) ? indexes.ipo : []) ensureCompany(record);
  for (const record of Array.isArray(indexes.bonds) ? indexes.bonds : []) {
    const company = ensureCompany(record);
    const bondCode = bondCodeOf(record);
    const bondName = bondNameOf(record);
    if (!company || !bondCode || !bondName) continue;
    if (!company.bonds.some((bond) => bond.code === bondCode)) {
      company.bonds.push({
        code: bondCode,
        label: bondName,
        href: `./bonds.html?bond=${encodeURIComponent(bondCode)}`,
      });
    }
  }

  return [...companies.values()]
    .filter((company) => recordMatches(needle, [
      company.code,
      company.label,
      ...company.bonds.flatMap((bond) => [bond.code, bond.label]),
    ]))
    .map((company) => ({
      kind: "公司",
      code: company.code,
      label: company.label,
      href: `./company.html?code=${encodeURIComponent(company.code)}`,
      bonds: company.bonds.sort((left, right) => left.code.localeCompare(right.code)),
    }))
    .sort((left, right) => (normalizePublicSearch(left.code) === needle ? -1 : 0)
      - (normalizePublicSearch(right.code) === needle ? -1 : 0)
      || left.code.localeCompare(right.code, "zh-Hant"))
    .slice(0, MAX_RESULTS);
}

export function searchPublicRecords(query, indexes = {}) {
  return buildCompanySearchResults(query, indexes);
}

function canonicalSearchValues(entry = {}) {
  return [
    entry.stockCode,
    entry.companyName,
    entry.cbCode,
    entry.cbName,
    ...(Array.isArray(entry.cbCodes) ? entry.cbCodes : []),
    ...(Array.isArray(entry.cbNames) ? entry.cbNames : []),
    ...(Array.isArray(entry.aliases) ? entry.aliases : []),
  ];
}

function canonicalSearchPriority(entry = {}, needle) {
  const isExact = (value) => normalizePublicSearch(value) === needle;
  const isPrefix = (value) => {
    const normalized = normalizePublicSearch(value);
    return normalized.length > needle.length && normalized.startsWith(needle);
  };
  if (entry.type === "cb" && /^\d{5,6}$/.test(needle) && isExact(entry.cbCode)) return 0;
  if (entry.type !== "cb" && isExact(entry.stockCode)) return 1;
  if (isExact(entry.companyName) || (Array.isArray(entry.aliases) && entry.aliases.some(isExact))) return 2;
  if (entry.type === "cb" && isExact(entry.cbName)) return 3;
  if (isExact(entry.stockCode)) return 4;
  if (canonicalSearchValues(entry).some(isPrefix)) return 4;
  return 5;
}

/**
 * Search only the public canonical index generated by the staging pipeline.
 * Exact CB codes deliberately rank ahead of their underlying company so that
 * a user entering a five-digit CB code lands on the bond detail page first.
 */
export function searchCanonicalIndex(query, index = []) {
  const needle = normalizePublicSearch(query);
  const entries = entriesOf(index);
  if (!needle || entries.length === 0) return [];
  return entries
    .filter((entry) => entry && recordMatches(needle, canonicalSearchValues(entry)))
    .map((entry) => ({
      id: safeText(entry.id),
      type: safeText(entry.type),
      stockCode: safeText(entry.stockCode),
      companyName: safeText(entry.companyName),
      cbCode: safeText(entry.cbCode),
      cbName: safeText(entry.cbName),
      market: safeText(entry.market),
      industry: safeText(entry.industry),
      url: safeText(entry.url),
      dataDate: safeText(entry.dataDate),
      activeEventLabel: safeText(entry.activeEventLabel),
      activeEventDate: safeText(entry.activeEventDate),
    }))
    .sort((left, right) => canonicalSearchPriority(left, needle) - canonicalSearchPriority(right, needle)
      || left.type.localeCompare(right.type, "zh-Hant")
      || `${left.stockCode}${left.cbCode}`.localeCompare(`${right.stockCode}${right.cbCode}`, "zh-Hant"))
    .slice(0, MAX_RESULTS);
}

export function searchStateMessage(state) {
  switch (state) {
    case "no_results": return "查無結果";
    case "not_ready": return "搜尋服務尚未就緒";
    case "load_error": return "搜尋資料載入失敗";
    case "network_error": return "暫時無法搜尋，請稍後再試";
    default: return "暫時無法搜尋，請稍後再試";
  }
}

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[character]));
}

async function fetchJson(url, fetchImpl = globalThis.fetch) {
  try {
    const response = await fetchImpl(url, { cache: "no-store" });
    if (!response.ok) return { state: "load_error", data: null };
    try {
      return { state: "ready", data: await response.json() };
    } catch {
      return { state: "load_error", data: null };
    }
  } catch {
    return { state: "network_error", data: null };
  }
}

export async function loadCanonicalSearchIndex({
  pointerUrl = "./data/current.json",
  baseUrl = globalThis.document?.baseURI ?? globalThis.location?.href,
  fetchImpl = globalThis.fetch,
} = {}) {
  if (typeof pointerUrl !== "string" || typeof baseUrl !== "string" || typeof fetchImpl !== "function") {
    return { state: "not_ready", entries: [] };
  }
  const pointerResponse = await fetchJson(pointerUrl, fetchImpl);
  if (pointerResponse.state !== "ready") return { state: pointerResponse.state, entries: [] };
  const pointer = pointerResponse.data;
  if (!pointer?.runtimeUrl) return { state: "not_ready", entries: [] };
  const runtimeResponse = await fetchJson(new URL(pointer.runtimeUrl, baseUrl), fetchImpl);
  if (runtimeResponse.state !== "ready") return { state: runtimeResponse.state, entries: [] };
  const runtime = runtimeResponse.data;
  if (typeof runtime?.v56MarketDataUrl === "string") {
    const v56Response = await fetchJson(new URL(runtime.v56MarketDataUrl, baseUrl), fetchImpl);
    const v56Entries = entriesOf(v56Response.data?.searchIndex);
    if (v56Response.state === "ready" && v56Response.data?.schemaVersion === 3 && Array.isArray(v56Response.data?.searchIndex?.records)) {
      return { state: "ready", entries: v56Entries };
    }
    if (typeof runtime?.searchIndexUrl !== "string") return { state: v56Response.state, entries: [] };
  }
  const searchUrl = runtime?.searchIndexUrl;
  if (!searchUrl) return { state: "not_ready", entries: [] };
  const searchResponse = await fetchJson(new URL(searchUrl, baseUrl), fetchImpl);
  if (searchResponse.state !== "ready") return { state: searchResponse.state, entries: [] };
  const entries = entriesOf(searchResponse.data);
  return entries.length || Array.isArray(searchResponse.data?.records)
    ? { state: "ready", entries }
    : { state: "load_error", entries: [] };
}

async function loadIndexes() {
  const config = globalThis.window?.__OFFICIAL_SHOWCASE__ ?? { generationPointerUrl: "./data/current.json" };
  return loadCanonicalSearchIndex({
    pointerUrl: config.generationPointerUrl,
    baseUrl: document.baseURI,
  });
}

export function isGlobalSearchShortcut(event = {}) {
  return Boolean((event.ctrlKey || event.metaKey)
    && !event.altKey
    && String(event.key ?? "").toLowerCase() === "k");
}

function canonicalResultTitle(row) {
  if (row.type === "cb") return `${row.cbCode} ${row.cbName}`.trim();
  return `${row.stockCode} ${row.companyName}`.trim();
}

function canonicalResultSubtitle(row, entries) {
  if (row.type === "cb") {
    const event = row.activeEventLabel
      ? `・${row.activeEventLabel}${row.activeEventDate ? ` ${row.activeEventDate.replaceAll("-", "/")}` : ""}`
      : "";
    return `可轉債・標的 ${row.stockCode} ${row.companyName}${event}`.trim();
  }
  const bondCount = entries.filter((entry) => entry.type === "cb" && entry.stockCode === row.stockCode).length;
  if (row.type === "ipo") return "IPO／公開發行研究";
  return bondCount ? `公司研究・${bondCount} 檔可轉債` : "公司研究";
}

export function buildSearchResultMarkup(query, indexState) {
  const needle = normalizePublicSearch(query);
  if (!needle) {
    return { count: 0, hidden: true, html: "" };
  }
  if (indexState?.state !== "ready") {
    return {
      count: 0,
      hidden: false,
      html: `<p class="search-result-state search-result-state--error" role="status">${escapeHtml(searchStateMessage(indexState?.state))}</p>`,
    };
  }
  const entries = indexState.entries ?? [];
  const matches = searchCanonicalIndex(needle, entries);
  return {
    count: matches.length,
    hidden: false,
    html: matches.length
      ? matches.map((row) => `<article class="search-result-card"><a role="option" href="${escapeHtml(row.url)}"><strong>${escapeHtml(canonicalResultTitle(row))}</strong><span>${escapeHtml(canonicalResultSubtitle(row, entries))}</span></a></article>`).join("")
      : `<p class="search-result-state" role="status">${escapeHtml(searchStateMessage("no_results"))}</p>`,
  };
}

function renderSearchResults(input, results, indexState) {
  const model = buildSearchResultMarkup(input?.value, indexState);
  results.hidden = model.hidden;
  results.innerHTML = model.html;
  return model.count;
}

function createHeaderSearch(header) {
  if (header.querySelector("[data-site-search]")) return header.querySelector("[data-site-search]");
  const form = document.createElement("form");
  form.className = "site-search";
  form.dataset.siteSearch = "";
  form.setAttribute("role", "search");
  form.innerHTML = '<button type="button" class="site-search__mobile-trigger" aria-label="開啟全站搜尋" aria-controls="site-search-results" aria-expanded="false">搜尋</button><label><span class="sr-only">搜尋公司、股票代碼、CB</span><input type="search" autocomplete="off" placeholder="搜尋公司、股票代碼、CB" aria-controls="site-search-results" aria-expanded="false"></label><div id="site-search-results" class="site-search__results" data-site-search-results role="listbox" hidden></div>';
  header.insertBefore(form, header.querySelector("#theme-toggle"));
  return form;
}

function bindSearchSurface(form, indexes) {
  if (!form || form.dataset.searchBound === "true") return null;
  const input = form.querySelector("input");
  const results = form.querySelector("[data-site-search-results]");
  const mobileTrigger = form.querySelector(".site-search__mobile-trigger");
  if (!input || !results) return null;
  form.dataset.searchBound = "true";
  let activeResultIndex = -1;
  const closeMobileSearch = () => {
    delete form.dataset.mobileOpen;
    mobileTrigger?.setAttribute("aria-expanded", "false");
    activeResultIndex = -1;
    input.setAttribute("aria-expanded", "false");
    results.hidden = true;
  };
  mobileTrigger?.addEventListener("click", () => {
    form.dataset.mobileOpen = "";
    mobileTrigger.setAttribute("aria-expanded", "true");
    input.focus();
  });
  form.addEventListener("submit", (event) => event.preventDefault());
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMobileSearch();
  });
  document.addEventListener("pointerdown", (event) => {
    if (!form.contains(event.target)) closeMobileSearch();
  });
  input.addEventListener("input", () => {
    const count = renderSearchResults(input, results, indexes);
    activeResultIndex = -1;
    input.setAttribute("aria-expanded", String(count > 0));
  });
  input.addEventListener("keydown", (event) => {
    const options = [...results.querySelectorAll('a[role="option"]')];
    if (event.key === "Escape") {
      event.preventDefault();
      closeMobileSearch();
      input.focus();
      return;
    }
    if (!options.length || !["ArrowDown", "ArrowUp", "Enter"].includes(event.key)) return;
    if (event.key === "Enter" && activeResultIndex >= 0) {
      event.preventDefault();
      options[activeResultIndex].click();
      return;
    }
    if (event.key === "Enter") return;
    event.preventDefault();
    activeResultIndex = event.key === "ArrowDown"
      ? (activeResultIndex + 1) % options.length
      : (activeResultIndex - 1 + options.length) % options.length;
    options[activeResultIndex].focus();
  });
  return { form, input, close: closeMobileSearch };
}

async function initializeSiteSearch() {
  const header = document.querySelector(".site-header__inner");
  if (!header) return;
  const headerForm = createHeaderSearch(header);
  const indexes = await loadIndexes();
  const surfaces = [
    bindSearchSurface(headerForm, indexes),
  ].filter(Boolean);
  const headerSurface = surfaces[0];
  document.addEventListener("keydown", (event) => {
    if (!isGlobalSearchShortcut(event)) return;
    event.preventDefault();
    if (headerSurface) {
      headerSurface.form.dataset.mobileOpen = "";
      headerSurface.input.focus();
    }
  });
}

if (globalThis.window && globalThis.document) initializeSiteSearch();
